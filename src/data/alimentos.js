/**
 * Catálogo de alimentos del generador de dietas.
 *
 * Aquí solo vive la clasificación dietética de cada alimento: qué papel hace
 * en el plato, qué alérgenos lleva, su índice glucémico, sus purinas, si es
 * alto en FODMAP y qué ración es razonable. Nada de eso lo publican las bases
 * de composición de alimentos, así que se mantiene a mano.
 *
 * Los valores nutricionales NO están aquí: se leen de nutricion-alimentos.json,
 * que se genera desde USDA FoodData Central y BEDCA con
 * `node scripts/generar-nutricion.mjs`. De ahí salen también el nombre y el
 * identificador del registro de origen, para que cada número sea rastreable.
 *
 * El potasio se clasifica a partir de los miligramos reales de la fuente
 * (importa en enfermedad renal), no a ojo.
 *
 * Campos:
 *   rol        proteina | carbohidrato | verdura | fruta | grasa | lacteo
 *   origen     vegetal | lacteo | huevo | pescado | marisco | carne | cerdo
 *   contiene   alérgenos e ingredientes que se filtran (gluten, lactosa, ...)
 *   ig         índice glucémico: bajo | medio | alto
 *   purinas    relevante en hiperuricemia y gota
 *   fodmap     bajo | alto — relevante en síndrome de intestino irritable
 *   racion     rango razonable en gramos y paso de ajuste del generador
 *   momentos   comidas del día en las que encaja
 */

