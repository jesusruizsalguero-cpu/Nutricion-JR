/** Umbrales de potasio por 100 g, para el filtro de enfermedad renal. */
function clasificarPotasio(miligramos) {
  if (!miligramos) return 'medio'
  if (miligramos >= 300) return 'alto'
  if (miligramos >= 150) return 'medio'
  return 'bajo'
}

