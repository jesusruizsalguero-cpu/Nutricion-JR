/** Une la clasificación con los valores de la fuente oficial. */
function montar(meta) {
  const datos = NUTRICION[meta.id]
  if (!datos) throw new Error(`Falta el dato nutricional de "${meta.id}" en nutricion-alimentos.json`)

  const [min, max, paso] = meta.racion
  return {
    id: meta.id,
    nombre: meta.nombre,
    rol: meta.rol,
    origen: meta.origen,

    kcal: datos.kcal,
    proteinas: datos.proteinas,
    carbohidratos: datos.carbohidratos,
    grasas: datos.grasas,
    saturadas: datos.saturadas,
    fibra: datos.fibra,
    sodio: datos.sodio,

    contiene: meta.contiene ?? [],
    ig: meta.ig ?? 'medio',
    purinas: meta.purinas ?? 'bajo',
    potasio: clasificarPotasio(datos.potasioMg),
    fodmap: meta.fodmap ?? 'bajo',
    racion: { min, max, paso },
    momentos: meta.momentos ?? TODAS,

    // Procedencia del dato, para poder comprobarlo (ver la pantalla /fuentes).
    fuente: datos.fuente,
    fuenteId: datos.fuenteId,
    fuenteNombre: datos.fuenteNombre,
  }
}

export const ALIMENTOS = CLASIFICACION.map(montar)

export const ALIMENTOS_POR_ID = Object.fromEntries(ALIMENTOS.map((x) => [x.id, x]))

/** Copia del alimento del catálogo, o null si el id no existe. */
export function obtenerAlimentoBase(id) {
  const alimento = ALIMENTOS_POR_ID[id]
  return alimento ? { ...alimento } : null
}
